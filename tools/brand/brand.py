#!/usr/bin/env python3
"""Generates Crosscast's vector icons from one definition of the logo.

The logo is three waves cast outward along each arm of an X ("cross" + "cast") around a dot.
Small sizes (the in-app symbol, the notification icon) use two waves per arm.

    python3 tools/brand/brand.py     # rewrites the drawables and prints the glyph paths for Glyphs.kt
Raster images (TV banner, README logo) come from tools/brand/render.swift.
"""
import math
from pathlib import Path

RES = Path(__file__).resolve().parents[2] / "app/src/main/res/drawable"

# (radius, half-angle in degrees) per wave, on a 100-unit tile; stroke 6.5, dot radius 6.5.
LOGO = [(13.0, 26.0), (23.5, 20.0), (34.0, 16.0)]
# The same on a 24-unit grid with two waves; stroke 1.9, dot radius 2.
SMALL = [(4.6, 26.0), (8.6, 20.0)]


def num(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def arc(cx, cy, r, mid, half):
    a1, a2 = math.radians(mid - half), math.radians(mid + half)
    return (f"M{num(cx + r * math.cos(a1))},{num(cy + r * math.sin(a1))} "
            f"A{num(r)},{num(r)} 0 0 1 {num(cx + r * math.cos(a2))},{num(cy + r * math.sin(a2))}")


def dot(cx, cy, r):
    return f"M{num(cx - r)},{num(cy)} A{num(r)},{num(r)} 0 1 0 {num(cx + r)},{num(cy)} A{num(r)},{num(r)} 0 1 0 {num(cx - r)},{num(cy)} Z"


def waves(cx, cy, spec, scale=1.0):
    return [arc(cx, cy, r * scale, 45 + 90 * k, half) for r, half in spec for k in range(4)]


def vector(comment, size, viewport, stroke, arcs, dot_path):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tools/brand/brand.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
    <path
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="{num(stroke)}"
        android:strokeLineCap="round"
        android:pathData="{" ".join(arcs)}" />
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{dot_path}" />
</vector>
'''


if __name__ == "__main__":
    u = 0.86  # 100-unit logo -> dp in a 108dp adaptive icon: the outer wave stays inside the 33dp safe radius
    (RES / "ic_launcher_foreground.xml").write_text(vector(
        "Crosscast's logo: waves cast outward along each arm of an X.", 108, 108, 6.5 * u,
        waves(54, 54, LOGO, u), dot(54, 54, 6.5 * u)))
    (RES / "ic_stat_speaker.xml").write_text(vector(
        "Crosscast's mark at notification size (white on transparent, as Android requires).", 24, 24, 1.9,
        waves(12, 12, SMALL), dot(12, 12, 2.0)))
    print("Glyphs.Cast arcs:", waves(12, 12, SMALL))
    print("Glyphs.Cast dot:", dot(12, 12, 2.0))
